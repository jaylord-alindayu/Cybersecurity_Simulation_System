<?php

require_once __DIR__ . '/config.php';

if (!isset($_SESSION['lab_balance'])) {
    $_SESSION['lab_balance'] = 100;
}

$notice = '';
$status = '';
$mode = 'protected';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {

    $mode = ($_POST['mode'] ?? 'protected') === 'unprotected'
        ? 'unprotected'
        : 'protected';

    $amount = max(0, min(100, (int)($_POST['amount'] ?? 0)));

    if ($mode === 'protected') {

        if (!csrf_valid()) {
            $notice = 'Request rejected: CSRF token is missing or invalid.';
            $status = 'error';

        } else {
            $_SESSION['lab_balance'] -= $amount;

            $notice = 'Protected request accepted. The simulated balance was updated.';
            $status = 'success';
        }

    } else {

        // Simulates the absence of CSRF validation.
        // This is a local session-only balance.

        $_SESSION['lab_balance'] -= $amount;

        $notice = 'Unprotected request accepted in the simulation. A real application could be tricked into performing an unwanted action.';
        $status = 'warning';
    }
}

page_header('CSRF');

?>

<div class="intro">
    <p>
        Cross-Site Request Forgery tricks a logged-in browser into sending
        an unwanted request. A CSRF token proves that the request came
        from a page generated by this application.
    </p>
</div>

<div class="two-col">

    <section class="panel">

        <h2>Simulated account action</h2>

        <div class="balance">
            <span>LAB BALANCE</span>

            <strong>
                ₱<?= number_format((int)$_SESSION['lab_balance']) ?>
            </strong>
        </div>

        <form method="post">

            <input type="hidden" name="csrf_token" value="<?= e(csrf_token()) ?>">

            <label>Amount to transfer (simulation only)</label>

            <input
                type="number"
                name="amount"
                min="0"
                max="100"
                value="10"
                required
            >

            <label>Request type</label>

            <select name="mode">

                <option value="protected">
                    Protected (validates token)
                </option>

                <option value="unprotected">
                    Unprotected (no token check)
                </option>

            </select>

            <button>Submit simulated request</button>

        </form>

        <?php if ($notice): ?>

            <div class="alert <?= e($status) ?>">
                <?= e($notice) ?>
            </div>

        <?php endif; ?>

        <p class="hint">
            This only changes a number stored in your local PHP session.
            It does not move real money.
        </p>

    </section>

    <aside class="panel">

        <h2>How protection works</h2>

        <ol>
            <li>
                Server creates a random token and stores it in the session.
            </li>

            <li>
                The page includes the token in the form.
            </li>

            <li>
                On POST, the server compares the submitted token using
                <code>hash_equals()</code>.
            </li>

            <li>
                If missing or incorrect, reject the request.
            </li>
        </ol>

        <pre><code>if (!hash_equals(
  $_SESSION['csrf_token'],
  $_POST['csrf_token']
)) {
  http_response_code(403);
  exit('Invalid CSRF token');
}</code></pre>

    </aside>

</div>

<?php page_footer(); ?>
